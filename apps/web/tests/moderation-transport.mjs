import assert from 'node:assert/strict'
import { webcrypto } from 'node:crypto'
import { prepareModeratedWrite, finishModeratedWrite, rememberModeratedVersions } from '../src/api/moderationTransport.js'
globalThis.crypto ||= webcrypto
const headers = () => ({ Authorization: 'Bearer isolated-moderation-transport' })
const options = body => ({ method: 'POST', body: JSON.stringify(body) })
const first=headers(),second=headers()
const intent=await prepareModeratedWrite('/posts',options({body:'same',title:'book'}),first)
await prepareModeratedWrite('/posts',options({title:'book',body:'same'}),second)
assert.equal(first['Idempotency-Key'],second['Idempotency-Key'],'Concurrent sends reuse one intent')
finishModeratedWrite(intent,false)
const retry=headers();await prepareModeratedWrite('/posts',options({body:'same',title:'book'}),retry)
assert.equal(first['Idempotency-Key'],retry['Idempotency-Key'],'Uncertain failures preserve retry identity')
finishModeratedWrite(intent,true)
const next=headers();await prepareModeratedWrite('/posts',options({body:'same',title:'book'}),next)
assert.notEqual(next['Idempotency-Key'],first['Idempotency-Key'],'A later successful repeat is a new intentional post')
const other={Authorization:'Bearer different-user'};await prepareModeratedWrite('/posts',options({body:'same',title:'book'}),other)
assert.notEqual(other['Idempotency-Key'],next['Idempotency-Key'],'User identities are isolated')
rememberModeratedVersions('/posts/post-1',{id:'post-1',moderation_version:3},headers())
const edit=headers();await prepareModeratedWrite('/posts/post-1',{method:'PUT',body:'{"body":"edit"}'},edit)
assert.equal(edit['If-Match'],'"3"')
rememberModeratedVersions('/posts/post-1',{id:'post-1',moderation_version:1},headers())
const delayed=headers();await prepareModeratedWrite('/posts/post-1',{method:'PUT',body:'{"body":"later"}'},delayed)
assert.equal(delayed['If-Match'],'"3"','Delayed responses cannot lower the known version')
const explicit={...headers(),'If-Match':'1'};await prepareModeratedWrite('/posts/post-1',{method:'PUT',body:'{"body":"edit"}'},explicit)
assert.equal(explicit['If-Match'],'1','The editor snapshot wins over a later cached read')
rememberModeratedVersions('/activities/review/a/comments',[{id:'comment',moderation_version:2}],headers())
const comment=headers();await prepareModeratedWrite('/activities/review/a/comments/comment',{method:'PUT',body:'{"body":"edit"}'},comment)
assert.equal(comment['If-Match'],'"2"')
const form=()=>{const data=new FormData();data.append('body','same');data.append('images',new Blob(['one'],{type:'image/png'}),'one.png');return data}
const fileA=headers(),fileB=headers()
await prepareModeratedWrite('/posts',{method:'POST',body:form()},fileA)
await prepareModeratedWrite('/posts',{method:'POST',body:form()},fileB)
assert.equal(fileA['Idempotency-Key'],fileB['Idempotency-Key'],'Multipart boundary does not change an intent')
const changed=form();changed.set('images',new Blob(['two'],{type:'image/png'}),'one.png')
const fileC=headers();await prepareModeratedWrite('/posts',{method:'POST',body:changed},fileC)
assert.notEqual(fileA['Idempotency-Key'],fileC['Idempotency-Key'],'File contents participate in the digest')
assert.equal(await prepareModeratedWrite('/readings/events',{method:'POST',body:'{}'},headers()),null,'Library writes are unchanged')
console.log('PASS: retry identity, concurrent requests, session isolation, multipart hashes, explicit/current versions and unchanged library transport')
